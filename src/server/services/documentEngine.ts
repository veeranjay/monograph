import { db } from '../db.js';
import crypto from 'node:crypto';
import { logEvent } from './eventEngine.js';

export interface DocumentRecord {
  id: string;
  object_id?: string | null;
  title: string;
  blocks: any[];
  latex_source?: string | null;
  created_at: string;
  updated_at: string;
  metadata: Record<string, any>;
}

export function getDocumentById(id: string): DocumentRecord | null {
  const row = db.prepare('SELECT * FROM documents WHERE id = ?').get(id) as any;
  if (!row) return null;
  return {
    ...row,
    blocks: safeJsonParseArray(row.blocks),
    metadata: safeJsonParseObject(row.metadata),
  };
}

export function getDocumentByObjectId(objectId: string): DocumentRecord | null {
  const row = db.prepare('SELECT * FROM documents WHERE object_id = ?').get(objectId) as any;
  if (!row) return null;
  return {
    ...row,
    blocks: safeJsonParseArray(row.blocks),
    metadata: safeJsonParseObject(row.metadata),
  };
}

export function createDocument(data: {
  id?: string;
  object_id?: string | null;
  title: string;
  blocks?: any[];
  latex_source?: string | null;
  metadata?: any;
}): DocumentRecord {
  const id = data.id || crypto.randomUUID();
  const now = new Date().toISOString();
  const blocksJson = JSON.stringify(data.blocks || []);
  const metaJson = JSON.stringify(data.metadata || {});

  db.prepare(`
    INSERT INTO documents (id, object_id, title, blocks, latex_source, created_at, updated_at, metadata)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
  `).run(
    id,
    data.object_id || null,
    data.title.trim(),
    blocksJson,
    data.latex_source || null,
    now,
    now,
    metaJson
  );

  if (data.object_id) {
    logEvent(data.object_id, 'document_created', { documentId: id, title: data.title });
  }

  return getDocumentById(id)!;
}

export function updateDocument(id: string, data: {
  title?: string;
  blocks?: any[];
  latex_source?: string | null;
  metadata?: any;
}): DocumentRecord {
  const existing = getDocumentById(id);
  if (!existing) throw new Error(`Document not found: ${id}`);

  const now = new Date().toISOString();
  const title = data.title !== undefined ? data.title.trim() : existing.title;
  const blocks = data.blocks !== undefined ? JSON.stringify(data.blocks) : JSON.stringify(existing.blocks);
  const latexSource = data.latex_source !== undefined ? data.latex_source : (existing.latex_source ?? null);
  const meta = data.metadata !== undefined ? JSON.stringify(data.metadata) : JSON.stringify(existing.metadata);

  db.prepare(`
    UPDATE documents
    SET title = ?, blocks = ?, latex_source = ?, updated_at = ?, metadata = ?
    WHERE id = ?
  `).run(title, blocks, latexSource ?? null, now, meta, id);

  if (existing.object_id) {
    logEvent(existing.object_id, 'document_updated', { documentId: id });
  }

  return getDocumentById(id)!;
}

export function exportDocumentToLatex(id: string): string {
  const doc = getDocumentById(id);
  if (!doc) throw new Error(`Document not found: ${id}`);

  let tex = `% Generated by Monograph Document Engine\n\\section{${doc.title}}\n\n`;

  for (const block of doc.blocks) {
    const type = block.type;
    const content = block.content || '';

    switch (type) {
      case 'h1':
        tex += `\\section{${content}}\n\n`;
        break;
      case 'h2':
        tex += `\\subsection{${content}}\n\n`;
        break;
      case 'h3':
        tex += `\\subsubsection{${content}}\n\n`;
        break;
      case 'math':
        tex += `\\begin{equation}\n${content}\n\\end{equation}\n\n`;
        break;
      case 'code':
        tex += `\\begin{verbatim}\n${content}\n\\end{verbatim}\n\n`;
        break;
      case 'bullet':
        tex += `\\begin{itemize}\n  \\item ${content}\n\\end{itemize}\n\n`;
        break;
      case 'numbered':
        tex += `\\begin{enumerate}\n  \\item ${content}\n\\end{enumerate}\n\n`;
        break;
      case 'divider':
        tex += `\\hrule\n\\vspace{0.5cm}\n\n`;
        break;
      default:
        tex += `${content}\n\n`;
        break;
    }
  }

  return tex;
}

function safeJsonParseArray(val: any): any[] {
  if (!val) return [];
  try {
    const parsed = typeof val === 'string' ? JSON.parse(val) : val;
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

function safeJsonParseObject(val: any): Record<string, any> {
  if (!val) return {};
  try { return typeof val === 'string' ? JSON.parse(val) : val; } catch { return {}; }
}
